// repo root. Two things drove the content:
//
//  · תיקון 13 לחוק הגנת הפרטיות came into force 14.8.2025. Its section 11
//    notice is now the operative duty for a business this size — at the
//    moment of collection you must say what the data is for, who controls
//    the database and how to reach them, who else receives it and why,
//    and that she may see and correct it. Registering the database is no
//    longer required at this scale; telling her plainly is.
//  · תקנות שוויון זכויות (התאמות נגישות לשירות) require an accessibility
//    statement naming a person to contact. Small turnover can exempt the
//    technical work; it does not remove the statement or the duty to
//    offer an accessible alternative route to the service.
